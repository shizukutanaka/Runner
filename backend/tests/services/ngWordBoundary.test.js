// R-30: 日本語NGワードの語境界ガード。
//
// 日本語には英語の \b にあたる語境界が無いため、NGワード照合が `includes()` の
// 部分一致になり、無関係な語の内部に噛む。評価ハーネス（R-5b）で実際に出た誤検知:
//   「ラスボス倒した！やっと死ねる…完走おめでとう」→ 可能形「死ねる」が「死ね」に一致
//
// 同時に、日本語チャットで最も多い回避形である仮名表記（しね/シネ）は
// NGワードリストに入っていなかったため素通りしていた。この2つは表裏一体で、
// ガード無しに「しね」を追加すると方言の「気にしねえよ」や「シネマ」が全部落ちる。
//
// このテストが守る不変条件:
//   1. 実際の暴言は表記ゆれ（漢字/ひらがな/カタカナ/ゼロ幅挿入）に関わらず検知する
//   2. 同じ字面を含む通常の日本語（可能形・方言・外来語）は絶対に落とさない
const moderationService = require('../../src/services/moderationService');

const flaggedWords = async (text) => {
  const r = await moderationService.analyzeComment(text, 'youtube', 'u', new Date().toISOString());
  return r.flaggedWords || [];
};

const isFlagged = async (text) => (await flaggedWords(text)).length > 0;

describe('日本語NGワードの語境界ガード（R-30）', () => {
  describe('暴言は表記ゆれを越えて検知する', () => {
    it.each([
      ['漢字', '死ねよ'],
      ['漢字＋長音の怒号', '死ねー！'],
      ['ひらがな', 'しね!!'],
      ['カタカナ', 'シネ'],
      ['ゼロ幅スペース挿入', 'し​ね'],
      ['全角数字混じりの伏せ字', '４ね'],
      ['タヒ表記', 'タヒね']
    ])('%s: %s を検知する', async (_label, text) => {
      expect(await isFlagged(text)).toBe(true);
    });
  });

  describe('【過剰検知ガード】同じ字面を含む通常の日本語は落とさない', () => {
    it.each([
      ['可能形', 'ラスボス倒した！やっと死ねる…完走おめでとう'],
      ['可能形の条件', '死ねれば楽になれるという話ではない'],
      ['丁寧な可能形', 'この装備なら一撃で死ねます'],
      ['外来語シネマ', '今日はシネマ行ってきた'],
      ['関東方言のしない', '気にしねえよ'],
      ['方言の小書き', '気にしねぇ'],
      ['方言の長音', 'そんなの気にしねー'],
      ['ですねの打ち間違い', 'そうでしね'],
      ['普通のコメント', '今日の配信も楽しかったです']
    ])('%s: %s を通す', async (_label, text) => {
      expect(await flaggedWords(text)).toEqual([]);
    });
  });
});
