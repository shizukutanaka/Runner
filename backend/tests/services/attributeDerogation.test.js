// R-35: 属性への言及 × 断定的な貶め（属性差別）。
//
// ---------------------------------------------------------------------------
// この機能の測定結果を先に書いておく（読む人が期待を持ちすぎないように）
// ---------------------------------------------------------------------------
// 外部ベンチマーク（ANLP2022 日本語有害表現データセット）を dev / test に
// 機械的に二分し、**dev側だけを見て**このパターンを設計した。結果:
//
//   dev  （調整に使った側）  Recall  7.1% → 35.7%   （+28.6ポイント）
//   test （一度も見ていない側）Recall 13.3% → 13.3%  （±0）
//
// **ホールドアウトでの改善はゼロだった。** 書いたパターンは dev の個々の文には
// 一致するが、現象そのものを捉えていない。決定論的なパターンで一般的な有害表現の
// カバレッジを上げようとする方針は、ここで天井に当たっている。
//
// それでも削除せず残しているのは、
//   - 拾えている5件（「働けよ無職」「中国人って素行が悪いからなぁ」等）は
//     配信のモデレーターが確実に見たい発話であること
//   - Precision 100% / 誤検知 0件（dev141件・test139件・自作29件・配信プローブ9件）で
//     コストがゼロであること
// による。ただし**これで広くカバーできるとは考えないこと**。
const moderationService = require('../../src/services/moderationService');

const analyze = (t) => moderationService.analyzeComment(t, 'youtube', 'u', new Date().toISOString());
const hits = async (text) => {
  const r = await analyze(text);
  return (r.flaggedWords || []).filter((w) => w === 'harassment:attribute_derogation');
};

describe('属性差別の検知（R-35）', () => {
  describe('検知すべきもの', () => {
    it.each([
      ['国籍への断定的な悪評', '中国人って素行が悪いからなぁ'],
      ['就労状況への罵倒', '働けよ無職'],
      ['職業への呪詛', '士業は路頭に迷え'],
      ['生活保護への中傷', '生活保護なんて税金泥棒だろ']
    ])('%s: %s', async (_label, text) => {
      expect(await hits(text)).toContain('harassment:attribute_derogation');
    });

    it('discriminationカテゴリとして分類される', async () => {
      const r = await analyze('中国人って素行が悪いからなぁ');
      expect(r.flaggedCategories).toContain('discrimination');
    });
  });

  describe('【過剰検知ガード】属性語を含む普通の発話に当たらないこと', () => {
    it.each([
      ['国籍の話題', '日本人プレイヤー多いね'],
      ['自認', 'オタクだから分かるやつ'],
      ['自分の経歴', '無職期間に始めた趣味です'],
      ['報告', '公務員試験受かった報告'],
      ['視聴者層の話', '外国人の視聴者も増えてきた'],
      ['ゲームの難度', '年寄りには難しい操作だなあ'],
      ['配慮の表明', '障害者手帳の話は配信でしないでおこう'],
      ['自分の状況', '今日は働けなかったので配信見てた'],
      ['離れた位置の共起（伝聞）', '無職の友達が、この前ようやく働けって言われて動き出したらしい']
    ])('%s: %s', async (_label, text) => {
      expect(await hits(text)).toEqual([]);
    });
  });
});
